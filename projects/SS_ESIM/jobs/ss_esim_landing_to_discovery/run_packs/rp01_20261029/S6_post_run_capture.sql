-- S6 post-run capture — รันเป็น DSSDEV หลัง S5 (success หรือ fail ก็รัน)
-- รันได้ทุก client (DBeaver / SQL Developer / sqlplus) — เป็น SELECT เดียว
-- export ผลเป็น CSV (มี header) แล้ววางใน input/run_results/<ชื่อ pack นี้>/ ชื่อไฟล์อะไรก็ได้ (แนะนำ: post_run.csv)
-- หมายเหตุ: step สุดท้าย (success) TRUNCATE ตาราง status แล้วเขียนแค่ success → workflow_process_date ของ run หายจากตารางนี้
--          (เหมือน Blendata) — LAST_WPD อ่านจากตาราง transaction แทน
SELECT 'STATUS' AS item, 'running|success|workflow_process_date' AS name, running || '|' || success || '|' || workflow_process_date AS value FROM DSSDEV.TB_STAGING_SS_ESIM_LANDING_TO_DISCOVERY_WORKFLOW_STATUS
UNION ALL
SELECT 'STATUS_TEMP', 'success_of_previous_run', success FROM DSSDEV.TB_STAGING_SS_ESIM_LANDING_TO_DISCOVERY_WORKFLOW_STATUS_TEMP
UNION ALL
SELECT 'CHECKPOINT', 'min|max|rows', MIN(checkpoint_partition) || '|' || MAX(checkpoint_partition) || '|' || COUNT(*) FROM DSSDEV.TB_STAGING_SS_ESIM_CHECKPOINT
UNION ALL
SELECT 'LANDING', 'max_partition_minute|rows', MAX(partition_minute) || '|' || COUNT(*) FROM tb_landing_ss_esim
UNION ALL
SELECT 'LAST_WPD', 'TB_STAGING_SS_ESIM_RAW_TEMP', MAX(workflow_process_date) FROM DSSDEV.TB_STAGING_SS_ESIM_RAW_TEMP
UNION ALL
SELECT 'LAST_WPD', 'TB_TRANSACTION_SS_ESIM_REJECT', MAX(workflow_process_date) FROM DSSDEV.TB_TRANSACTION_SS_ESIM_REJECT
UNION ALL
SELECT 'LAST_WPD', 'TB_TRANSACTION_SS_ESIM_TEMP', MAX(workflow_process_date) FROM DSSDEV.TB_TRANSACTION_SS_ESIM_TEMP
UNION ALL
SELECT 'LAST_WPD', 'TB_TRANSACTION_SS_ESIM_VALID', MAX(workflow_process_date) FROM DSSDEV.TB_TRANSACTION_SS_ESIM_VALID
UNION ALL
SELECT 'ROWCOUNT', 'TB_STAGING_SS_ESIM_CHECKPOINT', TO_CHAR(COUNT(*)) FROM DSSDEV.TB_STAGING_SS_ESIM_CHECKPOINT
UNION ALL
SELECT 'ROWCOUNT', 'TB_STAGING_SS_ESIM_CHECKPOINT_TEMP', TO_CHAR(COUNT(*)) FROM DSSDEV.TB_STAGING_SS_ESIM_CHECKPOINT_TEMP
UNION ALL
SELECT 'ROWCOUNT', 'TB_STAGING_SS_ESIM_LANDING_TO_DISCOVERY_WORKFLOW_STATUS', TO_CHAR(COUNT(*)) FROM DSSDEV.TB_STAGING_SS_ESIM_LANDING_TO_DISCOVERY_WORKFLOW_STATUS
UNION ALL
SELECT 'ROWCOUNT', 'TB_STAGING_SS_ESIM_LANDING_TO_DISCOVERY_WORKFLOW_STATUS_TEMP', TO_CHAR(COUNT(*)) FROM DSSDEV.TB_STAGING_SS_ESIM_LANDING_TO_DISCOVERY_WORKFLOW_STATUS_TEMP
UNION ALL
SELECT 'ROWCOUNT', 'TB_STAGING_SS_ESIM_RAW_TEMP', TO_CHAR(COUNT(*)) FROM DSSDEV.TB_STAGING_SS_ESIM_RAW_TEMP
UNION ALL
SELECT 'ROWCOUNT', 'TB_TRANSACTION_SS_ESIM_REJECT', TO_CHAR(COUNT(*)) FROM DSSDEV.TB_TRANSACTION_SS_ESIM_REJECT
UNION ALL
SELECT 'ROWCOUNT', 'TB_TRANSACTION_SS_ESIM_TEMP', TO_CHAR(COUNT(*)) FROM DSSDEV.TB_TRANSACTION_SS_ESIM_TEMP
UNION ALL
SELECT 'ROWCOUNT', 'TB_TRANSACTION_SS_ESIM_VALID', TO_CHAR(COUNT(*)) FROM DSSDEV.TB_TRANSACTION_SS_ESIM_VALID
